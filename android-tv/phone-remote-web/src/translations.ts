const russian = Object.fromEntries(
  Object.entries(english).map(([ru, en]) => [en, ru]),
);
export function translate(
  source: string,
  language: string,
  values: Record<string, unknown> = {},
  fallback?: string,
): string {
  const canonical = russian[source] || source;
  const text =
    language === "en" ? english[canonical] || fallback || source : canonical;
  return text.replace(/\{(v\d+)\}/g, (_, key: string) =>
    String(values[key] ?? ""),
  );
}
